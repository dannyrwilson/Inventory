def parse():
    """Returns [(parent_name, color, [child names])]."""
    tree = []
    for line in TAXONOMY_TEXT.splitlines():
        if not line.strip():
            continue
        if line.startswith((" ", "\t")):
            tree[-1][2].append(line.strip())
        else:
            tree.append((line.strip(), COLORS[len(tree) % len(COLORS)], []))
    return tree


TREE = parse()
